#define MLDSA_Q 8380417
#define MLDSA_D 13
#define ROOT_OF_UNITY 1753

#define MLDSA_K 4
#define MLDSA_L 4
#define MLDSA_ETA 2
#define MLDSA_TAU 39
#define MLDSA_BETA 78
#define MLDSA_GAMMA1 (1 << 17)
