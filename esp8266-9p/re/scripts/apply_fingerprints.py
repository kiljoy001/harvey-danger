#!/usr/bin/env python3
"""Generate B3Rename.java from fingerprint matches.

Only matches with >=3 agreeing code windows become renames, plus any
extra (symbol, addr) pairs passed as arguments for size+anchor
triangulated cases (e.g. wifi_mode_set). The generated script renames
the Ghidra function *containing* each image address, since Ghidra
boundaries may be off by the ENTRY opcode (B2 caveat).

Usage: apply_fingerprints.py <fingerprints.csv> <out.java>
       [symbol@0xaddr ...]
"""
import csv
import sys
from pathlib import Path

pairs = []
for r in csv.DictReader(open(sys.argv[1])):
    if r["image_addr"] and int(r["windows_hit"]) >= 3:
        pairs.append((r["symbol"], r["image_addr"], r["windows_hit"],
                      r["windows_total"], r["object"]))
for extra in sys.argv[3:]:
    sym, addr = extra.split("@")
    pairs.append((sym, addr, "size+anchor", "", "triangulated"))

lines = [
    "// B3Rename: generated by apply_fingerprints.py - SDK symbol names",
    "// matched by code-byte fingerprints (see B3 report).",
    "import ghidra.app.script.GhidraScript;",
    "import ghidra.program.model.address.Address;",
    "import ghidra.program.model.listing.Function;",
    "import ghidra.program.model.symbol.SourceType;",
    "",
    "public class B3Rename extends GhidraScript {",
    "    private void name(long addr, String name, String comment) throws Exception {",
    "        Address a = toAddr(addr);",
    "        Function f = getFunctionContaining(a);",
    "        if (f == null) { println(\"no function containing \" + Long.toHexString(addr)); return; }",
    "        f.setName(name, SourceType.USER_DEFINED);",
    "        f.setComment(comment);",
    "        println(\"named \" + f.getEntryPoint() + \" -> \" + name);",
    "    }",
    "    @Override public void run() throws Exception {",
]
for sym, addr, hit, total, obj in pairs:
    lines.append(f'        name({addr}L, "{sym}", '
                 f'"B3 SDK fingerprint: {hit}/{total} windows, object {obj}.");')
lines += ["    }", "}", ""]
Path(sys.argv[2]).write_text("\n".join(lines))
print(f"{len(pairs)} renames -> {sys.argv[2]}")
