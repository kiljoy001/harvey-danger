#!/usr/bin/env python3
import json
import sys
import os
import argparse

def main():
    parser = argparse.ArgumentParser(description="Harvey mksys generator")
    parser.add_argument("-mode", required=True, choices=["sys.h", "sysdecl.h", "syscallfiles", "systab.c", "error.h", "errstr.h", "all"])
    parser.add_argument("-o", dest="outpath", default="")
    parser.add_argument("-arch", choices=["amd64", "aarch64"], default="amd64",
                        help="assembly architecture for syscallfiles (default: amd64)")
    parser.add_argument("sysconf", help="Path to sysconf.json")
    args = parser.parse_args()

    with open(args.sysconf, "r") as f:
        conf = json.load(f)

    syscalls = conf.get("Syscalls", [])
    syserrors = conf.get("Syserrors", [])

    for sc in syscalls:
        if not sc.get("Define"):
            sc["Define"] = sc["Name"].upper()
        if not sc.get("Sysname"):
            sc["Sysname"] = "sys" + sc["Name"]
        if not sc.get("Libname"):
            sc["Libname"] = sc["Name"]

        ret0 = sc.get("Ret", ["int32_t"])[0]
        if ret0 == "int32_t" or ret0 == "i32":
            fudge = "{ .i = -1 }"
        elif ret0 == "int64_t" or ret0 == "i64":
            fudge = "{ .vl = -1ll }"
        elif ret0 == "void*":
            fudge = "{ .v = (void*)-1ll }"
        else:
            fudge = "{ .i = -1 }"
        sc["Fudge"] = fudge
        sc["Ret0"] = ret0

    mode = args.mode
    outpath = args.outpath

    if mode == "syscallfiles":
        dest_dir = outpath if outpath else "."
        os.makedirs(dest_dir, exist_ok=True)
        for sc in syscalls:
            s_path = os.path.join(dest_dir, f"{sc['Libname']}.s")
            with open(s_path, "w") as f:
                f.write("/* automatically generated by mksys.py */\n")
                f.write(f".globl\t{sc['Libname']}\n")
                f.write(f".type\t{sc['Libname']}, %function\n")
                f.write(f"{sc['Libname']}:\n")
                if args.arch == "aarch64":
                    f.write(f"\tmov x8, #{sc['Id']} /* syscall number */\n")
                    f.write("\tsvc #0\n")
                    f.write("\tret\n")
                else:
                    f.write("\tmovq %rcx, %r10 /* rcx gets smashed by syscall. Use r10. */\n")
                    f.write(f"\tmovq ${sc['Id']}, %rax /* syscall number */\n")
                    f.write("\tsyscall\n")
                    f.write("\tret\n")
        print(f"Generated {len(syscalls)} {args.arch} syscall assembly files in {dest_dir}")
        return

    content = ""
    if mode == "sys.h":
        content += "/* automatically generated by mksys.py */\n#pragma once\n\n"
        for sc in syscalls:
            content += f"#define {sc['Define']} {sc['Id']}\n"
    elif mode == "sysdecl.h":
        content += "/* automatically generated by mksys.py */\n#pragma once\n\n"
        for sc in syscalls:
            args_str = ", ".join(sc.get("Args", []))
            content += f"extern {sc['Ret0']} {sc['Libname']}({args_str});\n"
    elif mode == "systab.c":
        content += "/* automatically generated by mksys.py */\n"
        content += '#include "u.h"\n'
        content += '#include "../port/lib.h"\n'
        content += '#include "mem.h"\n'
        content += '#include "dat.h"\n'
        content += '#include "fns.h"\n'
        content += '#include "../port/error.h"\n\n'
        for sc in syscalls:
            content += f"extern void {sc['Sysname']}(Ar0*, ...);\n"
        max_id = max(sc["Id"] for sc in syscalls) if syscalls else 0
        content += f"\nSystab systab[{max_id + 1}] = {{\n"
        for sc in syscalls:
            content += f"    [{sc['Id']}] = {{ \"{sc['Name']}\", {sc['Sysname']}, {sc['Fudge']} }},\n"
        content += "};\n"
        content += f"int nsyscall = {max_id + 1};\n"
    elif mode == "error.h":
        content += "/* automatically generated by mksys.py */\n#pragma once\n\n"
        for err in syserrors:
            content += f"extern char {err['Name']}[]; /* {err['String']} */\n"
    elif mode == "errstr.h":
        content += "/* automatically generated by mksys.py */\n\n"
        for err in syserrors:
            content += f"char {err['Name']}[] = \"{err['String']}\";\n"

    if outpath:
        with open(outpath, "w") as f:
            f.write(content)
        print(f"Generated {outpath}")
    else:
        sys.stdout.write(content)

if __name__ == "__main__":
    main()
