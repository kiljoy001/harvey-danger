#!/usr/bin/env python3
import struct
import sys
import os

PT_LOAD = 1
PF_X = 1
PF_W = 2
PF_R = 4

def parse_elf(filepath):
    with open(filepath, "rb") as f:
        data = f.read()

    if data[:4] != b"\x7fELF":
        raise ValueError(f"{filepath} is not an ELF file")

    ei_class = data[4]
    if ei_class == 1: # 32-bit
        is_64 = False
        e_entry, e_phoff, e_shoff, e_flags, e_ehsize, e_phentsize, e_phnum = struct.unpack_from("<IIIIHHH", data, 24)
    elif ei_class == 2: # 64-bit
        is_64 = True
        e_entry, e_phoff, e_shoff, e_flags, e_ehsize, e_phentsize, e_phnum = struct.unpack_from("<QQQIHHH", data, 24)
    else:
        raise ValueError("Unknown ELF class")

    progs = []
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        if is_64:
            p_type, p_flags, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_align = struct.unpack_from("<IIQQQQQQ", data, off)
        else:
            p_type, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_flags, p_align = struct.unpack_from("<IIIIIIII", data, off)

        if p_type == PT_LOAD:
            seg_data = data[p_offset : p_offset + p_filesz]
            progs.append({
                "flags": p_flags,
                "vaddr": p_vaddr,
                "filesz": p_filesz,
                "memsz": p_memsz,
                "data": seg_data
            })

    return e_entry, progs

def gencode(name, seg_type, mem_dict, start, end):
    lines = []
    length = max(0, end - start)
    lines.append(f"int {name}_{seg_type}_start = {hex(start)};")
    lines.append(f"int {name}_{seg_type}_end = {hex(end)};")
    lines.append(f"int {name}_{seg_type}_len = {hex(length)};")
    if length == 0:
        lines.append(f"u8 {name}_{seg_type}_out[1] = {{ 0 }};")
    else:
        lines.append(f"u8 {name}_{seg_type}_out[] = {{")
        for i in range(start, end, 16):
            chunk = []
            for j in range(i, min(i + 16, end)):
                chunk.append(f"0x{mem_dict.get(j, 0):02x}")
            lines.append("    " + ", ".join(chunk) + ",")
        lines.append("};")
    return "\n".join(lines) + "\n"

def main():
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} <out.h> <input_elf>")
        sys.exit(1)

    out_file = sys.argv[1]
    in_elf = sys.argv[2]
    base_name = os.path.basename(in_elf).replace(".", "_")

    entry, progs = parse_elf(in_elf)

    codestart = 0x7fffffff
    codeend = -1
    datastart = 0x7fffffff
    dataend = -1

    mem_dict = {}

    for p in progs:
        vaddr = p["vaddr"]
        curstart = vaddr & ~0xfff
        curend = vaddr + p["memsz"]

        for i, b in enumerate(p["data"]):
            mem_dict[vaddr + i] = b

        # Executable segment -> code
        if p["flags"] & PF_X:
            if curstart < codestart:
                codestart = curstart
            if curend > codeend:
                codeend = curend
        # Writable or placed above text 2M boundary -> data
        elif (p["flags"] & PF_W) or (vaddr >= 0x400000):
            if curstart < datastart:
                datastart = curstart
            if curend > dataend:
                dataend = curend

    if codestart == 0x7fffffff:
        codestart = 0
        codeend = 0
    if datastart == 0x7fffffff:
        datastart = 0
        dataend = 0

    out = "/* Auto-generated by elf2c.py */\n#pragma once\n\n"
    out += f"usize {base_name}_main = {hex(entry)};\n\n"
    out += gencode(base_name, "code", mem_dict, codestart, codeend) + "\n"
    out += gencode(base_name, "data", mem_dict, datastart, dataend) + "\n"

    with open(out_file, "w") as f:
        f.write(out)

    print(f"Generated {out_file} from {in_elf} (code: {hex(codestart)}-{hex(codeend)}, data: {hex(datastart)}-{hex(dataend)})")

if __name__ == "__main__":
    main()
