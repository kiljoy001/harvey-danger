#!/usr/bin/env python3
"""Build the small libc-backed process embedded by the ARM64 boot test."""

from pathlib import Path
import argparse
import os
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[2]
BASE = 0x4000000000
CC = os.environ.get("ARM64_CC") or shutil.which("clang-23") or "clang"
LD = os.environ.get("ARM64_LD") or shutil.which("ld.lld") or "ld.lld"
NM = shutil.which("llvm-nm-23") or shutil.which("llvm-nm") or "llvm-nm"


def symbol_value(elf: Path, name: str) -> int:
    output = subprocess.run([NM, "-P", str(elf)], check=True, text=True,
                            capture_output=True).stdout
    for line in output.splitlines():
        fields = line.split()
        if fields and fields[0] == name:
            return int(fields[2], 16)
    raise RuntimeError(f"missing symbol {name}")


def emit_header(path: Path, image: bytes, entry: int, uarttype: int) -> None:
    if len(image) > 128 * 1024:
        raise RuntimeError(f"user probe ELF is unexpectedly large: {len(image)} bytes")
    if not BASE <= entry < BASE + 4096:
        raise RuntimeError("user probe entry is outside its RX page")
    if not BASE + 4096 <= uarttype < BASE + 8192 - 4:
        raise RuntimeError("user probe data is outside its RW page")
    lines = [
        "/* generated by util/arm64/build_user_probe.py */",
        f"#define ARM64USERPROBEUARTTYPE 0x{uarttype:x}ULL",
        f"static const u8 arm64userprobeelf[{len(image)}] = {{",
    ]
    for offset in range(0, len(image), 16):
        chunk = image[offset:offset + 16]
        lines.append("\t" + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend(("};", ""))
    path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    subprocess.run([sys.executable, str(ROOT / "util/arm64/build_libc.py")],
                   check=True, stdout=subprocess.DEVNULL)
    out = args.output.parent / "userprobe"
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    source = out / "probe.c"
    source.write_text(r'''#include <u.h>
#include <libc.h>
#include <tos.h>

u32 probeuarttype;

static void
uartputc(int c)
{
	volatile u32 *uart;

	uart = (volatile u32 *)0x4000003000ULL;
	if(probeuarttype == 1){
		while((uart[0x18/4] & (1U<<5)) != 0)
			;
	}else{
		while((uart[0x7c/4] & (1U<<1)) == 0)
			;
	}
	uart[0] = c;
}

static void
uartputs(char *s)
{
	while(*s != 0)
		uartputc(*s++);
}

void
main(int argc, char **argv)
{
	if(argc != 1 || argv != (char **)0x4000002000ULL || argv[0] != nil ||
	   _tos != (Tos *)0x4000002e00ULL || nsec() == 0){
		uartputs("HARVEY-ARM64 LIBC-USER FAIL\n");
		__asm__ volatile("mov x0, #58; svc #3");
	}else{
		uartputs("HARVEY-ARM64 LIBC-USER PASS\n");
		__asm__ volatile("mov x0, #57; svc #3");
	}
	for(;;)
		;
}
''')
    script = out / "probe.ld"
    script.write_text(f'''ENTRY(_main)
SECTIONS {{
  . = 0x{BASE:x};
  .text : {{ *(.text .text.*) }}
  .rodata : {{ *(.rodata .rodata.*) }}
  . = ALIGN(4096);
  .data : {{ *(.data .data.*) }}
  .bss : {{ *(.bss .bss.* COMMON) }}
}}
''')
    obj = out / "probe.o"
    elf = out / "probe.elf"
    subprocess.run([
        CC, "--target=aarch64-none-elf", "-ffreestanding", "-fno-builtin",
        "-fno-stack-protector", "-mstrict-align", "-O2",
        "-I", str(ROOT / "aarch64/include"),
        "-I", str(ROOT / "sys/include"), "-c", str(source), "-o", str(obj),
    ], check=True)
    subprocess.run([
        LD, "-z", "max-page-size=4096", "-T", str(script),
        "-e", "_main", "-u", "_main", str(obj),
        str(ROOT / "build/arm64-libc/libc.a"), "-o", str(elf),
    ], check=True)
    emit_header(args.output, elf.read_bytes(), symbol_value(elf, "_main"),
                symbol_value(elf, "probeuarttype"))


if __name__ == "__main__":
    main()
