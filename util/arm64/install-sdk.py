#!/usr/bin/env python3
"""Lay out a self-contained Harvey/ARM64 SDK around a native clang.

Copies the cross-built clang, ld.lld and llvm-ar, clang's resource headers,
the Harvey and APEX include trees, the runtime archives and the link script
into one directory, and writes driver configs whose paths are the *guest*
paths, so the tree can be shipped to the board or a QEMU guest and used as
is:

    util/arm64/install-sdk.py                     # build/arm64-sdk, /sdk
    util/arm64/install-sdk.py --root /arm --out /tmp/sdk

`clang` then finds its config through InstalledDir, its resource headers
under lib/clang/<ver>/include, and the link recipe's libs under lib/.
"""
from pathlib import Path
import argparse
import os
import shutil
import subprocess
import struct
import sys
import tarfile
import io

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
CLANG_VERSION = "22"
LLVM_STRIP = None  # set from --llvm in main()

CONFIG = """\
# Harvey/ARM64 toolchain (generated by util/arm64/install-sdk.py)
-target aarch64-unknown-linux-elf
-nostdlibinc
-mstrict-align
-mno-outline-atomics
-fno-stack-protector
-D_SUSV2_SOURCE -D_POSIX_SOURCE -D_LIMITS_EXTENSION -D_GNU_SOURCE -DHARVEY
-I{root}/include
-I{root}/include/machine
-I{root}/include/target
-I{root}/include/c++
-I{root}/include/c++/v1
-I{root}/include/apex
-I{root}/include/apex/aarch64
{extra}
"""

LINK = """\
-nostdlib -static -no-pie -fuse-ld=lld
-T {root}/apex.ld -Wl,-u,_start
-Wl,-z,max-page-size=4096 -Wl,--eh-frame-hdr
${root}/lib/libc++.a
${root}/lib/libunwind.a
${root}/lib/libap.a
${root}/lib/libc.a
${root}/lib/libbuiltins.a
"""


CLANG_TOOLS = ("clangd", "clang-tidy", "clang-check", "clang-format",
               "clang-apply-replacements", "clang-query", "clang-doc",
               "clang-include-cleaner", "clang-include-fixer",
               "clang-move", "clang-reorder-fields", "modularize",
               "pp-trace")

EXTRAS = {"clang-doc", "clang-include-cleaner", "clang-include-fixer",
          "clang-move", "clang-reorder-fields", "modularize", "pp-trace"}

# LLVM tools that are not part of the multicall driver in this version.
STANDALONE_TOOLS = ("llvm-as", "llvm-dis", "llc", "opt", "llvm-link",
                    "llvm-lto", "llvm-mc", "llvm-dwarfdump",
                    "llvm-strings", "llvm-profdata", "llvm-cov",
                    "llvm-extract", "llvm-diff", "llvm-bcanalyzer")

# Tools whose installed name does not carry the llvm- prefix.
BARE_TOOLS = {"clang", "clang++", "clang-cl", "clang-cpp",
              "clang-scan-deps", "clang-installapi", "lld", "ld.lld",
              "lld-link", "ld64.lld", "wasm-ld", "ld", "dsymutil"}


def driver_tools(llvm: Path):
    """Names the llvm multicall binary dispatches on (argv[0])."""
    names = []
    defs = llvm / "tools" / "llvm-driver" / "LLVMDriverTools.def"
    if defs.is_file():
        for line in defs.read_text().splitlines():
            if not line.startswith('LLVM_DRIVER_TOOL("'):
                continue
            tool = line.split('"')[1]
            names.append(tool if tool in BARE_TOOLS else "llvm-" + tool)
    if not names:
        names = ["llvm-ar", "llvm-ranlib", "llvm-nm", "llvm-objcopy",
                 "llvm-strip", "llvm-objdump", "llvm-readobj",
                 "llvm-readelf", "llvm-size", "llvm-strings",
                 "llvm-symbolizer", "llvm-cxxfilt", "llvm-addr2line"]
    return names


def strip_binary(path: Path) -> None:
    """Strip a shipped tool; the guest does not debug the tools themselves."""
    if LLVM_STRIP is None:
        return
    subprocess.run([str(LLVM_STRIP), "--strip-all", str(path)], check=True)


def copy_tree(src: Path, dst: Path, pattern="*") -> int:
    n = 0
    for path in src.rglob(pattern):
        if not path.is_file():
            continue
        target = dst / path.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
        n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--llvm", default="/tmp/opencode/llvm-arm64-full",
                    help="build tree with bin/clang-22 and bin/lld")
    ap.add_argument("--out", default=str(ROOT / "build" / "arm64-sdk"))
    ap.add_argument("--root", default="/initramfs/sdk",
                    help="where the tree will live in the guest")
    ap.add_argument("--no-cxx-alias", action="store_true",
                    help="omit the clang++ copy (invoke clang -x c++ "
                         "instead; saves a second copy of the binary)")
    ap.add_argument("--with-ar", action="store_true",
                    help="also ship llvm-ar and llvm-ranlib")
    ap.add_argument("--with-tools", action="store_true",
                    help="ship the llvm multicall driver and the "
                         "clang-tools-extra utilities")
    ap.add_argument("--driver-only", action="store_true",
                    help="ship only the multicall driver for clang and "
                         "lld instead of standalone copies of both")
    ap.add_argument("--no-extras", action="store_true",
                    help="skip the clang-tools-extra utilities that are not "
                         "part of a normal compile/format/tidy workflow")
    ap.add_argument("--board-sdk", action="store_true",
                    help="leave out the large analysis binaries; the board "
                         "has to hold the archive and its unpacked copy in "
                         "the same RAM bank")
    ap.add_argument("--tar", default="",
                    help="also write a ustar archive of the tree (as "
                         "sdk/...)")
    ap.add_argument("--boot-archive", default="",
                    help="write an O9BOOT01 boot archive holding that tar "
                         "as /boot/sdk.tar")
    ap.add_argument("--no-strip", action="store_true",
                    help="keep debug sections in the shipped tools")
    args = ap.parse_args()

    llvm = Path(args.llvm)
    clang = llvm / "bin" / "clang-22"
    lld = llvm / "bin" / "lld"
    global LLVM_STRIP
    if not args.no_strip:
        # The build tree's llvm-strip is the guest multicall driver (an
        # ARM64 binary), so only the host tool can strip the shipped ELFs.
        for candidate in (Path(shutil.which("llvm-strip") or ""),
                          llvm / "bin" / "llvm-strip"):
            if candidate.is_file() and os.access(candidate, os.X_OK):
                LLVM_STRIP = candidate
                break
    for path in (clang, lld):
        if not path.is_file():
            sys.exit(f"missing {path}; build clang for aarch64 first")

    out = Path(args.out)
    shutil.rmtree(out, ignore_errors=True)
    (out / "bin").mkdir(parents=True)
    (out / "lib").mkdir()
    (out / "include").mkdir()
    (out / "tmp").mkdir()

    # One real copy of each large binary, with symlinks for the aliases the
    # driver selects on argv[0].  Copying clang three times wasted a
    # quarter of the archive.
    tools = [] if args.driver_only else [("clang-22", clang), ("lld", lld)]
    for name, src in tools:
        if src.is_file():
            shutil.copyfile(src, out / "bin" / name)
            os.chmod(out / "bin" / name, 0o755)
            strip_binary(out / "bin" / name)
    # The guest has no symbolic links, so aliases are tiny shims that
    # re-exec the multicall driver with argv[0] preserved.
    root = args.root.rstrip("/")
    shim = None
    driver = llvm / "bin" / "llvm"
    if args.with_tools and driver.is_file():
        shutil.copyfile(driver, out / "bin" / "llvm")
        os.chmod(out / "bin" / "llvm", 0o755)
        strip_binary(out / "bin" / "llvm")
        shim = out / "bin" / "llvm-shim"
        shim_src = out / "bin" / "llvm-shim.c"
        text = (HERE / "llvm-shim.c").read_text()
        text = text.replace('#define SDK_ROOT "/initramfs/sdk"',
                            f'#define SDK_ROOT "{root}"')
        shim_src.write_text(text)
        subprocess.run([str(HERE / "aarch64-clang"), "-O2",
                        str(shim_src), "-o", str(shim)], check=True)
        shim_src.unlink()
        strip_binary(shim)

    aliases = [("clang", "clang-22"), ("clang-cpp", "clang-22"),
               ("clang-cl", "clang-22")]
    if not args.no_cxx_alias:
        aliases.append(("clang++", "clang-22"))
    aliases += [("ld.lld", "lld"), ("lld-link", "lld"),
                ("ld64.lld", "lld"), ("wasm-ld", "lld"), ("ld", "lld")]
    for name, target in aliases:
        link = out / "bin" / name
        if link.exists() or link.is_symlink():
            link.unlink()
        if shim is not None:
            shutil.copyfile(shim, link)
            os.chmod(link, 0o755)
        else:
            os.symlink(target, link)

    if shim is not None:
        for name in driver_tools(llvm):
            if name in ("clang", "clang++", "clang-cl", "clang-cpp",
                        "ld.lld", "lld-link", "ld64.lld", "wasm-ld", "ld"):
                continue
            dst = out / "bin" / name
            if dst.exists():
                continue
            shutil.copyfile(shim, dst)
            os.chmod(dst, 0o755)
        shim.unlink(missing_ok=True)

    if args.with_ar:
        # llvm-ar/ranlib came from the driver above when it is available.
        ar = llvm / "bin" / "llvm-ar"
        if ar.is_file() and not (out / "bin" / "llvm-ar").exists():
            tools += [("llvm-ar", ar), ("llvm-ranlib", ar)]
            for name, src in tools[-2:]:
                shutil.copyfile(src, out / "bin" / name)
                os.chmod(out / "bin" / name, 0o755)
                strip_binary(out / "bin" / name)

    if args.with_tools:
        names = list(STANDALONE_TOOLS) + list(CLANG_TOOLS)
        if args.no_extras or args.board_sdk:
            names = [n for n in names if n not in EXTRAS]
        if args.board_sdk:
            names = [n for n in names
                     if n not in ("clang-tidy", "clang-check", "clang-query")]
        for name in names:
            src = llvm / "bin" / name
            if not src.is_file():
                continue
            dst = out / "bin" / name
            shutil.copyfile(src, dst)
            os.chmod(dst, 0o755)
            strip_binary(dst)

    headers = llvm / "lib" / "clang" / CLANG_VERSION / "include"
    if not headers.is_dir():
        sys.exit(f"missing clang resource headers at {headers}")
    copy_tree(headers, out / "lib" / "clang" / CLANG_VERSION / "include")

    # Include trees, mirroring what util/arm64/aarch64-clang passes.
    for src, dst in (
            (ROOT / "util" / "arm64" / "include", out / "include" / "machine"),
            (ROOT / "util" / "clang-harvey" / "target-include",
             out / "include" / "target"),
            (ROOT / "apex" / "include", out / "include" / "apex"),
            (ROOT / "apex" / "aarch64" / "include",
             out / "include" / "apex" / "aarch64")):
        if not src.is_dir():
            sys.exit(f"missing {src}")
        copy_tree(src, dst)

    libcxx = ROOT / "build" / "arm64-libcxx" / "include"
    if not libcxx.is_dir():
        sys.exit("missing build/arm64-libcxx; run build_libcxx.py first")
    copy_tree(libcxx / "c++", out / "include" / "c++")
    for name in ("compat.h", "pthread.h", "sched.h", "cxxabi.h",
                 "__cxxabi_config.h"):
        if (libcxx / name).is_file():
            shutil.copyfile(libcxx / name, out / "include" / name)

    for name in ("libc++.a", "libunwind.a"):
        shutil.copyfile(ROOT / "build" / "arm64-libcxx" / "lib" / name,
                        out / "lib" / name)
    for name in ("libap.a", "libbuiltins.a"):
        shutil.copyfile(ROOT / "build" / "arm64-apex" / name,
                        out / "lib" / name)
    shutil.copyfile(ROOT / "build" / "arm64-libc" / "libc.a",
                    out / "lib" / "libc.a")
    shutil.copyfile(HERE / "apex.ld", out / "apex.ld")

    (out / "bin" / "clang.cfg").write_text(CONFIG.format(
        root=root, extra="") + LINK.format(root=root))
    (out / "bin" / "clang++.cfg").write_text(CONFIG.format(
        root=root, extra="-fexceptions -frtti -D_WCHAR_T\n"
                         f"-include {root}/include/compat.h") +
        LINK.format(root=root))
    blob = None
    if args.tar or args.boot_archive:
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w",
                          format=tarfile.USTAR_FORMAT) as tar:
            for path in sorted(out.rglob("*")):
                rel = "sdk/" + path.relative_to(out).as_posix()
                if path.is_symlink():
                    info = tarfile.TarInfo(rel)
                    info.type = tarfile.SYMTYPE
                    info.linkname = os.readlink(path)
                    info.mode = 0o755
                    tar.addfile(info)
                elif path.is_dir():
                    info = tarfile.TarInfo(rel)
                    info.type = tarfile.DIRTYPE
                    info.mode = 0o755
                    tar.addfile(info)
                elif path.is_file():
                    info = tar.gettarinfo(str(path), arcname=rel)
                    with open(path, "rb") as handle:
                        tar.addfile(info, handle)
        blob = buf.getvalue()
        if args.tar:
            Path(args.tar).write_bytes(blob)
            print(f"ARM64 SDK tar: {args.tar} ({len(blob)} bytes)")
        if args.boot_archive:
            name = b"sdk.tar"
            total = 24 + 48 + len(blob)
            header = struct.pack("<8sIIII", b"O9BOOT01", 1, 1, total, 0)
            entry = struct.pack("<32sIIII", name, 24 + 48, len(blob),
                                0o555, 0)
            Path(args.boot_archive).write_bytes(header + entry + blob)

    print(f"ARM64 SDK: {out} (guest root {root})")


if __name__ == "__main__":
    main()
